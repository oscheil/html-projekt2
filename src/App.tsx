function parseSizeToBytes(value: string, unit: string): number {
  const num = parseFloat(value);
  if (isNaN(num)) return 0;
  const multipliers: Record<string, number> = {
    'B': 1,
    'KB': 1024,
    'MB': 1024 * 1024,
    'GB': 1024 * 1024 * 1024,
    'TB': 1024 * 1024 * 1024 * 1024,
  };
  return Math.round(num * (multipliers[unit] || 1));
}

function getLineColor(line: string): string {
  const trimmed = line.trim();
  if (trimmed.startsWith('#') || trimmed.startsWith('"""')) return 'text-gray-500';
  if (trimmed.startsWith('def ') || trimmed.startsWith('class ')) return 'text-blue-400';
  if (trimmed.startsWith('import ') || trimmed.startsWith('from ')) return 'text-purple-400';
  if (trimmed.startsWith('if ') || trimmed.startsWith('for ') || trimmed.startsWith('else') || trimmed.startsWith('try') || trimmed.startsWith('except')) return 'text-yellow-400';
  if (trimmed.startsWith('return ') || trimmed.startsWith('print(')) return 'text-green-400';
  if (trimmed.includes('= ') && !trimmed.startsWith(' ') && !trimmed.startsWith('#')) return 'text-cyan-400';
  return 'text-gray-300';
}
